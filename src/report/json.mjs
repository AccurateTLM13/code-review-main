// JSON report: stable, CI-friendly, agent-friendly (schemaVersion 1).
export function buildJsonReport(report) {
  return JSON.stringify({
    schemaVersion: 1,
    generator: { name: 'code-audit', version: report.meta.version },
    meta: {
      timestamp: report.meta.timestamp,
      target: report.meta.target,
      git: report.meta.git ?? null,
      depth: report.meta.depth,
      focus: report.meta.focus,
      changed: report.meta.changed,
      changedBasis: report.meta.changedBasis ?? null,
      changedFiles: report.meta.changedFiles ?? null,
      deletedFiles: report.meta.deletedFiles ?? [],
      failOn: report.meta.failOn,
      durationMs: report.meta.durationMs,
      exitCode: report.meta.exitCode,
      redaction: report.meta.redaction ?? 'on',
      configSources: report.meta.configSources ?? [],
      coverage: report.meta.coverage ?? null,
      partial: report.meta.partial ?? false,
      partialReasons: report.meta.partialReasons ?? [],
    },
    repo: {
      totalSourceFiles: report.repo.totalSourceFiles,
      totalLoc: report.repo.totalLoc,
      languages: report.repo.languages,
      stacks: report.repo.stacks,
      entryPoints: report.repo.entryPoints,
      docs: report.repo.docs,
      hotspots: report.repo.hotspots,
      graph: report.repo.graph,
    },
    stats: report.stats,
    models: report.meta.models,
    runs: report.runs,
    checksExecuted: report.checksExecuted,
    notes: report.notes,
    findings: report.findings.map(slimFinding),
    backlog: {
      quickWins: report.backlog.quickWins.map((f) => f.id),
      planned: report.backlog.planned.map((f) => f.id),
      investigate: report.backlog.investigate.map((f) => f.id),
      dismissed: (report.backlog.dismissed ?? []).map((f) => f.id),
    },
  }, null, 2);
}

function slimFinding(f) {
  return {
    id: f.id,
    checkId: f.checkId,
    source: f.source,
    kind: f.kind ?? undefined,
    consensus: f.consensus ?? false,
    consensusBy: f.consensusBy ?? undefined,
    category: f.category,
    severity: f.severity,
    confidence: f.confidence,
    priority: f.priority,
    effort: f.effort,
    title: f.title,
    description: f.description,
    file: f.file,
    lines: f.lines,
    snippet: f.snippet,
    occurrences: f.occurrences,
    suggestion: f.suggestion,
    benefit: f.benefit,
    risk: f.risk,
    verified: f.verified,
    verification: f.verification,
    scope: f.scope ?? 'full',
    dismissed: f.dismissed ?? false,
    dismissedBy: f.dismissedBy ?? undefined,
    contested: f.contested ?? false,
    tags: f.tags,
    modelVerdicts: f.modelVerdicts,
  };
}
